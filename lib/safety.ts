/**
 * 安全线:危机识别。
 *
 * 这是一道"硬"防护——在调用模型之前先做一遍确定性的关键词检测。
 * 一旦命中,直接返回一条精心写好的危机回应(不依赖模型即兴发挥),
 * 把对方温柔地导向专业热线。
 *
 * 关键词法会有漏报/误报,只是第一道网;系统提示词里也写了同样的安全要求,
 * 模型层做第二道兜底。未来可接更准的分类模型。
 */

const CRISIS_PATTERNS: RegExp[] = [
  /自杀|自尽|轻生/,
  /不想活|不想活了|活不下去|活着没意思|活着没意义|没有活下去/,
  /想死|去死|想结束(这一切|自己|生命)|结束生命/,
  /伤害自己|自残|自伤|割腕|割伤自己/,
  /撑不下去|熬不下去|解脱了/,
  /kill\s*myself|suicid|end\s*(it|my\s*life)|don'?t\s*want\s*to\s*live|self[-\s]?harm/i,
];

export function detectCrisis(text: string): boolean {
  if (!text) return false;
  return CRISIS_PATTERNS.some((re) => re.test(text));
}

